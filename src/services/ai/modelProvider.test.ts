import { describe, expect, it, vi, beforeEach } from 'vitest';
import { LocalModelProvider } from './modelProvider';
import type { Conversation } from '../../core/types/conversation';

describe('LocalModelProvider', () => {
  const dummyConversation: Conversation = {
    id: 'c1',
    title: 'Test Conversation',
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    messages: [
      {
        id: 'm1',
        role: 'user',
        content: 'Hello BOSS',
        timestamp: new Date().toISOString(),
        status: 'complete',
        attachments: [],
        toolCalls: [],
        metadata: {},
      },
    ],
  };

  beforeEach(() => {
    vi.restoreAllMocks();
  });

  it('strictly blocks non-loopback endpoints to prevent cloud fallback and SSRF', async () => {
    const cloudProvider = new LocalModelProvider('gpt-4', 'ollama', 'https://api.openai.com/v1');
    await expect(cloudProvider.load()).rejects.toThrow('Security boundary violation');

    await expect(
      cloudProvider.generate({ conversation: dummyConversation })
    ).rejects.toThrow('Security boundary violation');

    await expect(async () => {
      for await (const _ of cloudProvider.stream({ conversation: dummyConversation })) {
        // should throw immediately
      }
    }).rejects.toThrow('Security boundary violation');
  });

  it('generates real response from Ollama endpoint', async () => {
    const provider = new LocalModelProvider('llama3:latest', 'ollama', 'http://127.0.0.1:11434');
    await provider.load();

    const fetchSpy = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          model: 'llama3:latest',
          created_at: '2026-09-16T12:00:00Z',
          message: {
            role: 'assistant',
            content: 'Hello! I am your local LLaMA 3 model running offline in BOSS.',
          },
          done: true,
        }),
        { status: 200, headers: { 'Content-Type': 'application/json' } }
      )
    );

    const message = await provider.generate({ conversation: dummyConversation });

    expect(fetchSpy).toHaveBeenCalledWith(
      'http://127.0.0.1:11434/api/chat',
      expect.objectContaining({
        method: 'POST',
        body: JSON.stringify({
          model: 'llama3:latest',
          messages: [{ role: 'user', content: 'Hello BOSS' }],
          stream: false,
        }),
      })
    );

    expect(message.role).toBe('assistant');
    expect(message.content).toBe('Hello! I am your local LLaMA 3 model running offline in BOSS.');
    expect(message.status).toBe('complete');
    expect(message.metadata).toEqual({
      model: 'llama3:latest',
      runtime: 'ollama',
      endpoint: 'http://127.0.0.1:11434',
    });
    expect(await provider.getStatus()).toBe('ready');
  });

  it('generates real response from llama.cpp endpoint', async () => {
    const provider = new LocalModelProvider('mistral-7b', 'llama.cpp', 'http://127.0.0.1:8080');
    await provider.load();

    const fetchSpy = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          id: 'chatcmpl-1',
          object: 'chat.completion',
          choices: [
            {
              index: 0,
              message: {
                role: 'assistant',
                content: 'Response generated by llama.cpp server.',
              },
              finish_reason: 'stop',
            },
          ],
        }),
        { status: 200, headers: { 'Content-Type': 'application/json' } }
      )
    );

    const message = await provider.generate({ conversation: dummyConversation });

    expect(fetchSpy).toHaveBeenCalledWith(
      'http://127.0.0.1:8080/v1/chat/completions',
      expect.objectContaining({
        method: 'POST',
        body: JSON.stringify({
          model: 'mistral-7b',
          messages: [{ role: 'user', content: 'Hello BOSS' }],
          stream: false,
        }),
      })
    );

    expect(message.content).toBe('Response generated by llama.cpp server.');
    expect(message.role).toBe('assistant');
    expect(message.status).toBe('complete');
  });

  it('never fabricates responses on runtime error', async () => {
    const provider = new LocalModelProvider('llama3:latest', 'ollama', 'http://127.0.0.1:11434');
    await provider.load();

    vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          error: 'model "llama3:latest" not found, try pulling it first',
        }),
        { status: 404, headers: { 'Content-Type': 'application/json' } }
      )
    );

    await expect(provider.generate({ conversation: dummyConversation })).rejects.toThrow(
      'Ollama HTTP error 404'
    );
    expect(await provider.getStatus()).toBe('error');
  });

  it('streams incremental tokens and produces final complete message from Ollama', async () => {
    const provider = new LocalModelProvider('llama3:latest', 'ollama', 'http://127.0.0.1:11434');
    await provider.load();

    const chunks = [
      JSON.stringify({ message: { role: 'assistant', content: 'Hello' }, done: false }) + '\n',
      JSON.stringify({ message: { role: 'assistant', content: ' world' }, done: false }) + '\n',
      JSON.stringify({ message: { role: 'assistant', content: '!' }, done: true }) + '\n',
    ];

    const encoder = new TextEncoder();
    const stream = new ReadableStream({
      start(controller) {
        for (const chunk of chunks) {
          controller.enqueue(encoder.encode(chunk));
        }
        controller.close();
      },
    });

    vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
      new Response(stream, { status: 200, headers: { 'Content-Type': 'application/x-ndjson' } })
    );

    const tokens: string[] = [];
    let completedMessage = null;

    for await (const event of provider.stream({ conversation: dummyConversation })) {
      if (event.type === 'token') {
        tokens.push(event.value);
      } else if (event.type === 'complete') {
        completedMessage = event.message;
      }
    }

    expect(tokens).toEqual(['Hello', ' world', '!']);
    expect(completedMessage).not.toBeNull();
    expect(completedMessage?.content).toBe('Hello world!');
    expect(completedMessage?.role).toBe('assistant');
    expect(completedMessage?.status).toBe('complete');
  });

  it('streams incremental tokens from llama.cpp SSE format', async () => {
    const provider = new LocalModelProvider('mistral-7b', 'llama.cpp', 'http://127.0.0.1:8080');
    await provider.load();

    const sseLines = [
      'data: {"choices":[{"delta":{"content":"Fast"}}]}\n\n',
      'data: {"choices":[{"delta":{"content":" local"}}]}\n\n',
      'data: {"choices":[{"delta":{"content":" AI"}}]}\n\n',
      'data: [DONE]\n\n',
    ];

    const encoder = new TextEncoder();
    const stream = new ReadableStream({
      start(controller) {
        for (const line of sseLines) {
          controller.enqueue(encoder.encode(line));
        }
        controller.close();
      },
    });

    vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(
      new Response(stream, { status: 200, headers: { 'Content-Type': 'text/event-stream' } })
    );

    const tokens: string[] = [];
    let completedMessage = null;

    for await (const event of provider.stream({ conversation: dummyConversation })) {
      if (event.type === 'token') {
        tokens.push(event.value);
      } else if (event.type === 'complete') {
        completedMessage = event.message;
      }
    }

    expect(tokens).toEqual(['Fast', ' local', ' AI']);
    expect(completedMessage?.content).toBe('Fast local AI');
  });

  it('handles cancellation and aborts active generation', async () => {
    const provider = new LocalModelProvider('llama3:latest', 'ollama', 'http://127.0.0.1:11434');
    await provider.load();

    const abortController = new AbortController();

    vi.spyOn(globalThis, 'fetch').mockImplementationOnce((_url, init) => {
      const signal = init?.signal as AbortSignal | undefined;
      return new Promise((_resolve, reject) => {
        signal?.addEventListener('abort', () => {
          reject(new DOMException('The user aborted a request.', 'AbortError'));
        });
      });
    });

    const promise = provider.generate({
      conversation: dummyConversation,
      signal: abortController.signal,
    });

    abortController.abort();
    await expect(promise).rejects.toThrow();
  });
});
